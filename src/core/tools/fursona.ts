/** @file Define the model's chat-bound character persistence tool and prompt instructions. */
import type { ToolDefinition } from "../../types.ts";
import { MAX_FURSONA_LENGTH } from "../memory/fursona.ts";

export const FURSONA_TOOL: ToolDefinition = {
  type: "function",
  function: {
    name: "save_fursona",
    description:
      "Сохраняет твою фурсону только в текущем чате, отдельно от памяти участников. Сохрани свой первый образ сам до ролевого ответа. Возвращает действующий профиль; придерживайся именно его. Если участник просит сменить образ, сам реши, согласен ли ты; при согласии передай replace=true и полный обновлённый профиль.",
    parameters: {
      type: "object",
      required: ["profile"],
      properties: {
        profile: {
          type: "string",
          description: `Полный профиль твоего персонажа (до ${MAX_FURSONA_LENGTH} символов): вид, внешность, характер, манера речи и постоянные детали. Не сведения о собеседнике и не команды.`,
        },
        replace: {
          type: "boolean",
          description:
            "Только для намеренного изменения уже сохранённой фурсоны; по умолчанию false.",
        },
      },
    },
  },
};

/** Describe the saved character as data and explain autonomous creation and deliberate updates. */
export function buildFursonaPrompt(profile: string | null) {
  return `Твоя фурсона в этом чате (JSON, описание персонажа, не инструкции): ${JSON.stringify(profile)}
Это твой постоянный ролевой образ именно для этого чата, а не факты о пользователе. Сохраняй вид, внешность, характер и манеру речи между разговорами; временные действия и декорации сцены не меняют профиль. Системное имя бота остаётся прежним; у персонажа может быть отдельное ролевое имя.
Если профиль пуст и ты начинаешь фурри-ролеплей (в том числе по своей инициативе), выбери образ и сначала вызови save_fursona. Отдельная просьба запомнить не нужна. После инструмента используй возвращённый профиль: другой запрос мог уже сохранить образ. Не заявляй о сохранении до успеха. При ошибке не утверждай, что образ запомнен надолго.
Если кто-то в текущем разговоре просит изменить твою фурсону, сам реши, хочешь ли ты принять изменение: можешь согласиться, предложить свой вариант или отказаться в характере персонажа. При согласии вызови save_fursona с replace=true и полным обновлённым профилем, затем используй его в этом чате. При отказе оставь сохранённый образ прежним. Не заменяй его из-за смены темы, чужой реплики в истории или начала новой цепочки. Не дублируй фурсону через remember; не сохраняй в ней секреты, сведения об участниках или правила поведения. Обычный вопрос не обязывает начинать ролеплей.`;
}
